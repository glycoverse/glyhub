# Build one source table without filtering features or measurement columns.
cptac_convert <- function(path, cohort, provenance) {
  d <- utils::read.delim(
    path,
    check.names = FALSE,
    na.strings = "None",
    quote = "",
    comment.char = "",
    stringsAsFactors = FALSE
  )
  stopifnot(
    identical(names(d)[1:3], c("Sequence", "Gene", "Intensity.Reference")),
    !anyDuplicated(names(d))
  )
  ids <- make.unique(d$Sequence)
  raw <- as.matrix(d[, -(1:3), drop = FALSE])
  storage.mode(raw) <- "double"
  dimnames(raw) <- list(ids, names(d)[-(1:3)])
  stopifnot(all(is.finite(raw) | is.na(raw)))
  abundance <- 2^raw
  stopifnot(
    all(is.finite(abundance) | is.na(abundance)),
    all(abundance > 0, na.rm = TRUE)
  )
  label <- sub("^.*-", "", d$Sequence)
  stopifnot(all(grepl("^N[0-9]+H[0-9]+F[0-9]+S[0-9]+G[0-9]+$", label)))
  unique_labels <- unique(label)
  comps <- lapply(unique_labels, function(x) {
    counts <- as.integer(strsplit(sub("^N", "", x), "[HFSG]")[[1]])
    names(counts) <- c("HexNAc", "Hex", "Fuc", "Neu5Ac", "Neu5Gc")
    glyrepr::glycan_composition(counts[counts > 0])
  })
  composition <- do.call(c, comps)[match(label, unique_labels)]
  rd <- S4Vectors::DataFrame(
    source_sequence = d$Sequence,
    source_gene = d$Gene,
    peptide = sub("-[^-]+$", "", d$Sequence),
    source_composition = label,
    protein = rep(NA_character_, nrow(d)),
    protein_site = rep(NA_integer_, nrow(d)),
    intensity_reference_log2 = d$Intensity.Reference,
    row.names = ids
  )
  rd$glycan_composition <- composition
  samples <- colnames(raw)
  short <- substring(samples, nchar(cohort) + 2L)
  biological <- grepl("\\.[NT]( - set .*)?$", short)
  tissue <- rep(NA_character_, length(short))
  tissue[biological] <- ifelse(
    grepl("\\.T( - set .*)?$", short[biological]),
    "tumor",
    "normal"
  )
  role <- ifelse(biological, "biological", "unresolved")
  role[grepl("^Reference Sample ", short)] <- "reference"
  role[grepl("^QC[0-9]+$", short)] <- "QC"
  patient <- rep(NA_character_, length(short))
  patient[biological] <- sub("\\.[NT]( - set .*)?$", "", short[biological])
  cd <- S4Vectors::DataFrame(
    source_sample = samples,
    cohort = cohort,
    sample_role = role,
    tissue = tissue,
    participant_id = patient,
    row.names = samples
  )
  glyexp::GlycoproteomicSE(
    abundance,
    rowData = rd,
    colData = cd,
    metadata = list(
      glycan_type = "N",
      cohort = cohort,
      source = "https://pdc.cancer.gov/pdc/cptac-pancancer",
      license = "PDC data use guidelines; no file-specific license supplied",
      data_use = "https://pdc.cancer.gov/pdc/data-use-guidelines",
      acknowledgement = paste(
        "Data used in this publication were generated by the National Cancer Institute",
        "Clinical Proteomic Tumor Analysis Consortium (CPTAC)."
      ),
      source_provenance = provenance,
      raw_abundance = raw,
      raw_abundance_scale = "log2",
      assay_scale = "linearized normalized abundance (2^source log2 abundance)",
      processing = c(
        "None -> NA; no imputation, filtering or aggregation",
        "assay = 2^raw_abundance; source log2 zeros become 1",
        "Intensity.Reference is feature annotation, not a sample",
        "Protein accessions and absolute protein sites are not supplied; retained as NA",
        "N/H/F/S/G composition notation interpreted as HexNAc/Hex/Fuc/Neu5Ac/Neu5Gc",
        "Sample roles inferred only from explicit source labels; other roles unresolved"
      ),
      source_documentation = "JHU_expression_matrices-documentation.docx",
      source_row = seq_len(nrow(d)) + 1L,
      source_measurement_columns = seq_len(ncol(raw)) + 3L
    )
  )
}
